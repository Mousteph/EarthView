import assert from 'node:assert/strict';
import test from 'node:test';
import { startEnrichmentPolling } from '../features/severe-events/enrichmentPolling.ts';
import { SEVERE_EVENT_REFRESH_INTERVAL_MS } from '../features/severe-events/refreshPolicy.ts';
const valid = (value) => typeof value === 'number';
const flush = async () => { for(let i=0;i<6;i++) await Promise.resolve(); };

test('loads immediately, refreshes at six minutes, stops when disabled, and reloads on re-enable', async (t) => {
  t.mock.timers.enable({ apis: ['setInterval'] });
  const fetch = t.mock.method(globalThis, 'fetch', async () => ({ ok: true, json: async () => 12 }));
  const values = [];
  const callbacks = { loading: () => {}, success: (v) => values.push(v), failure: assert.fail };
  let stop = startEnrichmentPolling('/api/severe-events/overlays', valid, callbacks);
  await flush();
  assert.deepEqual(values, [12]);
  t.mock.timers.tick(SEVERE_EVENT_REFRESH_INTERVAL_MS - 1);
  assert.equal(fetch.mock.callCount(), 1);
  t.mock.timers.tick(1);
  await flush();
  assert.equal(fetch.mock.callCount(), 2);
  stop();
  t.mock.timers.tick(SEVERE_EVENT_REFRESH_INTERVAL_MS);
  assert.equal(fetch.mock.callCount(), 2);
  stop = startEnrichmentPolling('/api/severe-events/overlays', valid, callbacks);
  await flush();
  assert.equal(fetch.mock.callCount(), 3);
  stop();
});
test('late responses after selection changes are ignored and aborted', async (t) => {
  t.mock.timers.enable({ apis: ['setInterval'] });
  let finish;
  let signal;
  t.mock.method(globalThis, 'fetch', (_url, options) => { signal=options.signal; return new Promise((resolve) => { finish=resolve; }); });
  const values = [];
  const stop = startEnrichmentPolling('/api/severe-events/DR/12/details', valid, { loading: () => {}, success: (v) => values.push(v), failure: assert.fail });
  stop();
  assert.equal(signal.aborted, true);
  finish({ ok: true, json: async () => 12 });
  await flush();
  assert.deepEqual(values, []);
});
test('failed or invalid refreshes surface errors without replacing last good data', async (t) => {
  t.mock.timers.enable({ apis: ['setInterval'] });
  let response = { ok: true, json: async () => 12 };
  t.mock.method(globalThis, 'fetch', async () => response);
  let data = null;
  const errors=[];
  const stop = startEnrichmentPolling('/api/severe-events/overlays', valid, { loading: () => {}, success: (v) => { data=v; }, failure: (message) => errors.push(message) });
  await flush();
  response = { ok: false };
  t.mock.timers.tick(SEVERE_EVENT_REFRESH_INTERVAL_MS);
  await flush();
  assert.equal(data, 12);
  assert.match(errors[0], /temporarily unavailable/);
  response = { ok: true, json: async () => ({ wrong: 'shape' }) };
  t.mock.timers.tick(SEVERE_EVENT_REFRESH_INTERVAL_MS);
  await flush();
  assert.equal(data, 12);
  assert.match(errors[1], /invalid format/);
  stop();
});
